#!/usr/bin/env python3
"""
Migration Script: Transition to OAuth2 Authentication

This script helps migrate from the non-OAuth version of Gemini Chat
to the OAuth2-enabled version.
"""

import os
import sqlite3
import shutil
import json
from datetime import datetime
from pathlib import Path

def backup_existing_data():
    """Backup existing chat history and configuration"""
    print("🔄 Creating backup of existing data...")
    
    backup_dir = Path("backup_" + datetime.now().strftime("%Y%m%d_%H%M%S"))
    backup_dir.mkdir(exist_ok=True)
    
    # Backup chat history database
    if os.path.exists("chat_history.db"):
        shutil.copy2("chat_history.db", backup_dir / "chat_history.db")
        print(f"✅ Backed up chat_history.db to {backup_dir}")
    
    # Backup .env file
    if os.path.exists(".env"):
        shutil.copy2(".env", backup_dir / ".env")
        print(f"✅ Backed up .env to {backup_dir}")
    
    # Backup allowed_context directory
    if os.path.exists("allowed_context"):
        shutil.copytree("allowed_context", backup_dir / "allowed_context")
        print(f"✅ Backed up allowed_context to {backup_dir}")
    
    return backup_dir

def update_database_schema():
    """Update database schema to include user associations"""
    print("🔄 Updating database schema...")
    
    if not os.path.exists("chat_history.db"):
        print("⚠️  No existing chat_history.db found. New database will be created.")
        return
    
    try:
        with sqlite3.connect("chat_history.db") as conn:
            cursor = conn.cursor()
            
            # Check if user_id column exists
            cursor.execute("PRAGMA table_info(history)")
            columns = [column[1] for column in cursor.fetchall()]
            
            if 'user_id' not in columns:
                # Add user_id column to existing history table
                cursor.execute("ALTER TABLE history ADD COLUMN user_id TEXT")
                print("✅ Added user_id column to history table")
            else:
                print("✅ Database schema already updated")
            
            conn.commit()
            
    except Exception as e:
        print(f"❌ Error updating database schema: {e}")
        return False
    
    return True

def create_oauth_env_file():
    """Create OAuth2 environment configuration"""
    print("🔄 Setting up OAuth2 configuration...")
    
    # Read existing .env if it exists
    existing_config = {}
    if os.path.exists(".env"):
        with open(".env", "r") as f:
            for line in f:
                if "=" in line and not line.strip().startswith("#"):
                    key, value = line.strip().split("=", 1)
                    existing_config[key] = value
    
    # Create new .env with OAuth2 settings
    oauth_config = {
        "GOOGLE_API_KEY": existing_config.get("GOOGLE_API_KEY", "your_google_api_key_here"),
        "SECRET_KEY": existing_config.get("SECRET_KEY", "your_super_secret_key_change_this_in_production"),
        "OAUTH2_PROVIDER": "google",
        "GOOGLE_CLIENT_ID": "your_google_client_id.apps.googleusercontent.com",
        "GOOGLE_CLIENT_SECRET": "your_google_client_secret",
        "ENABLE_ROLE_BASED_ACCESS": "true",
        "DEFAULT_USER_ROLE": "user",
        "ADMIN_EMAILS": "admin@example.com",
        "ENABLE_RATE_LIMITING": "true",
        "RATE_LIMIT_PER_USER": "100"
    }
    
    # Write new .env file
    with open(".env.oauth", "w") as f:
        f.write("# Gemini Chat OAuth2 Configuration\n")
        f.write("# Generated by migration script\n\n")
        
        for key, value in oauth_config.items():
            f.write(f"{key}={value}\n")
        
        f.write("\n# Instructions:\n")
        f.write("# 1. Set up OAuth2 credentials with your provider\n")
        f.write("# 2. Update the OAuth2 client ID and secret above\n")
        f.write("# 3. Add admin email addresses\n")
        f.write("# 4. Rename this file to .env\n")
    
    print("✅ Created .env.oauth with OAuth2 configuration")
    print("📝 Please update OAuth2 credentials and rename to .env")

def install_oauth_dependencies():
    """Install OAuth2 dependencies"""
    print("🔄 Installing OAuth2 dependencies...")
    
    try:
        import subprocess
        result = subprocess.run([
            "pip", "install", 
            "Flask-Login==0.6.3",
            "Authlib==1.3.0", 
            "requests-oauthlib==1.3.1",
            "cryptography==41.0.7"
        ], capture_output=True, text=True)
        
        if result.returncode == 0:
            print("✅ OAuth2 dependencies installed successfully")
        else:
            print(f"⚠️  Warning: Some dependencies may not have installed correctly")
            print(f"Error: {result.stderr}")
            print("Please run: pip install -r requirements-oauth.txt")
    
    except Exception as e:
        print(f"⚠️  Could not automatically install dependencies: {e}")
        print("Please run: pip install -r requirements-oauth.txt")

