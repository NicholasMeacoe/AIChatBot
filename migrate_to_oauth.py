def main():
    """Main migration function"""
    print("🚀 Starting migration to OAuth2 authentication...")
    print("=" * 50)
    
    # Step 1: Backup existing data
    backup_dir = backup_existing_data()
    
    # Step 2: Update database schema
    if not update_database_schema():
        print("❌ Database migration failed. Check backup and try again.")
        return
    
    # Step 3: Create OAuth2 configuration
    create_oauth_env_file()
    
    # Step 4: Install dependencies
    install_oauth_dependencies()
    
    # Step 5: Create summary
    create_migration_summary()
    
    print("=" * 50)
    print("🎉 Migration completed successfully!")
    print(f"📁 Backup created in: {backup_dir}")
    print("📖 Next steps in: MIGRATION_SUMMARY.md")
    print("⚠️  Remember to set up OAuth2 credentials before running the app!")

if __name__ == "__main__":
    main()
